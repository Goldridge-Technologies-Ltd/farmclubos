/*
  Checks the commit message against the Conventional Commits format documented
  in CONTRIBUTING.md. Run by the commit-msg hook.
*/
import { readFileSync } from "node:fs";

const TYPES = [
  "feat",
  "fix",
  "chore",
  "refactor",
  "docs",
  "test",
  "perf",
  "build",
  "ci",
  "revert",
];

const SCOPES = ["api", "webapp", "site", "design-system", "docs", "repo"];

// type(scope/module)!: subject — scope and module are optional, "!" marks a
// breaking change.
const PATTERN = new RegExp(
  `^(${TYPES.join("|")})` +
    `(\\((${SCOPES.join("|")})(\\/[a-z0-9-]+)?\\))?` +
    `!?: .{1,72}$`,
);

const path = process.argv[2];
const message = readFileSync(path, "utf8");

// The first non-comment line is the subject; git appends its own comments.
const subject = message
  .split("\n")
  .find((line) => line.trim() && !line.startsWith("#"))
  ?.trim();

// Merges and reverts are generated by git itself.
const generated = /^(Merge|Revert) /.test(subject ?? "");

if (!subject || (!generated && !PATTERN.test(subject))) {
  console.error(`
Commit message does not follow the project format.

  Got: ${subject ?? "(empty)"}

  Expected: <type>(<scope>): <subject>

  Types:  ${TYPES.join(", ")}
  Scopes: ${SCOPES.join(", ")} — optionally scope/module, such as api/auth

  Examples:
    feat(api/auth): add email and password sign-in
    fix(webapp/dashboard): await searchParams before reading filters
    chore(design-system): add the gold badge tone

  The subject is at most 72 characters. See CONTRIBUTING.md.
`);
  process.exit(1);
}
